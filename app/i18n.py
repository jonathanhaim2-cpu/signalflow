"""Locale cookie, html dir, and UI strings for English (default) and Hebrew."""

from __future__ import annotations

from typing import Any
from urllib.parse import urlencode

from starlette.requests import Request

COOKIE_NAME = "sf_lang"
SUPPORTED = ("en", "he")
DEFAULT_LOCALE = "en"
COOKIE_MAX_AGE = 365 * 24 * 3600


def apply_locale_cookie(response, locale: str) -> None:
    if locale not in SUPPORTED:
        locale = DEFAULT_LOCALE
    response.set_cookie(
        COOKIE_NAME,
        locale,
        max_age=COOKIE_MAX_AGE,
        path="/",
        samesite="lax",
        httponly=False,
    )

# Keys that must never appear in rendered HTML (either locale).
BANNED_PHRASES = (
    "מחו״ל",
    'מחו"ל',
    "קבלה מחו",
    "חשבונית זרה",
    "foreign invoice",
    "foreign receipt",
    "foreign receipts",
    "תנסו מחר",
    "try again tomorrow",
    "try tomorrow",
)


def parse_locale(value: str | None) -> str | None:
    if not value:
        return None
    raw = value.strip().lower()
    if raw in SUPPORTED:
        return raw
    if raw.startswith("he"):
        return "he"
    if raw.startswith("en"):
        return "en"
    return None


def locale_from_request(request: Request) -> str:
    state = getattr(request, "state", None)
    if state is not None:
        current = getattr(state, "locale", None)
        if current in SUPPORTED:
            return current
    query = parse_locale(request.query_params.get("lang"))
    if query:
        return query
    cookie = parse_locale(request.cookies.get(COOKIE_NAME))
    if cookie:
        return cookie
    return DEFAULT_LOCALE


def dir_for(locale: str) -> str:
    return "rtl" if locale == "he" else "ltr"


def lang_href(request: Request, lang: str) -> str:
    params = [(k, v) for k, v in request.query_params.multi_items() if k != "lang"]
    params.append(("lang", lang))
    return f"{request.url.path}?{urlencode(params)}"


def lookup(tree: dict[str, Any], key: str) -> Any:
    node: Any = tree
    for part in key.split("."):
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node


def t(locale: str, key: str, **kwargs: Any) -> str:
    lang = locale if locale in SUPPORTED else DEFAULT_LOCALE
    value = lookup(STRINGS[lang], key)
    if value is None and lang != DEFAULT_LOCALE:
        value = lookup(STRINGS[DEFAULT_LOCALE], key)
    if value is None:
        value = key
    text = str(value)
    if kwargs:
        return text.format(**kwargs)
    return text


def js_bundle(locale: str) -> dict[str, str]:
    lang = locale if locale in SUPPORTED else DEFAULT_LOCALE
    bundle = lookup(STRINGS[lang], "js")
    if not isinstance(bundle, dict):
        bundle = lookup(STRINGS[DEFAULT_LOCALE], "js") or {}
    return {str(k): str(v) for k, v in bundle.items()}


def api_message(request: Request | None, key: str, **kwargs: Any) -> str:
    locale = locale_from_request(request) if request is not None else DEFAULT_LOCALE
    return t(locale, key, **kwargs)


